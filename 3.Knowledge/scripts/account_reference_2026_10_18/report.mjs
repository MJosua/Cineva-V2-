import fs from 'node:fs/promises';
import path from 'node:path';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const root = path.resolve(import.meta.dirname, '../../..'), out = path.join(root, '3.Knowledge/reports/account_reference_2026_10_18');
const selection = JSON.parse(await fs.readFile(path.join(out, 'selection.json'), 'utf8'));
const tests = JSON.parse(await fs.readFile(path.join(out, 'e2e-results.json'), 'utf8'));
if (tests.checks.length !== 4 || tests.checks.some(c => c.status !== 'passed')) throw new Error('Tests failed');
const w = Workbook.create(), s = w.worksheets.add('Akun referensi');
s.showGridLines = false;
s.getRange('A2').values = [['Cineva: tiga akun referensi tersamarkan']];
s.getRange('A2').format.font = { name: 'Arial', size: 14, bold: true, color: '#61411F' };
s.getRange('A3').values = [['Snapshot hanya baca; bukan login atau transaksi terverifikasi. Sumber asli tidak diubah.']];
s.getRange('A3').format.font = { name: 'Arial', size: 11, italic: true };
s.getRange('A5:D8').values = [['Alias', 'Sumber workbook / sheet', 'Baris roster', 'Baris lanjutan'], ...selection.selection.map((a, i) => [`Akun Referensi ${i + 1}`, `${a.sourceFile} / ${a.sheet}`, a.sourceRow, a.detailRow])];
s.getRange('A5:D8').format.font = { name: 'Arial', size: 11 };
s.getRange('A5:D8').format.wrapText = true;
s.getRange('A5:D8').format.rowHeight = 44;
s.getRange('A5:D5').format.fill = '#483326';
s.getRange('A5:D5').format.font = { name: 'Arial', size: 11, bold: true, color: '#FFFFFF' };
for (const [col, width] of [['A', 25], ['B', 79], ['C', 17], ['D', 19]]) s.getRange(`${col}2:${col}18`).format.columnWidth = width;
s.getRange('C6:D8').setNumberFormat('0');
s.getRange('A11:B15').values = [['Kontrol', 'Hasil'], ['Privasi', 'Nama/handle/kontak/alamat/URL tidak diekspor. Alias dan koordinat sumber saja.'], ['Finansial', 'Fee dan paid_amount belum tersedia; teks/tanggal payment tidak dianggap bukti kas.'], ['E2E', '4 skenario lulus menggunakan fixture sintetis, bukan akun asli.'], ['Sumber audit', 'selection.json, e2e-results.json dan architecture/account_reference_2026_10_18.md']];
s.getRange('A11:B15').format.font = { name: 'Arial', size: 11 };
s.getRange('A11:B15').format.wrapText = true;
s.getRange('A11:B15').format.rowHeight = 38;
s.getRange('A11:B11').format.fill = '#483326';
s.getRange('A11:B11').format.font = { name: 'Arial', size: 11, bold: true, color: '#FFFFFF' };
w.recalculate();
await fs.writeFile(path.join(out, 'workbook-errors.json'), (await w.inspect({ kind: 'match', searchTerm: '#REF!|#DIV/0!|#VALUE!|#NAME\\?', options: { useRegex: true, maxResults: 20 }, maxChars: 500 })).ndjson);
await (await SpreadsheetFile.exportXlsx(w)).save(path.join(out, 'Cineva_Account_Reference.xlsx'));
const preview = await w.render({ sheetName: s.name, range: 'A1:D16', scale: 1 });
await fs.writeFile(path.join(out, 'report-preview.png'), new Uint8Array(await preview.arrayBuffer()));
