import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
const root = path.resolve(import.meta.dirname, '../../..');
const require = createRequire(path.join(root, '1.Frontend/HOTS/package.json'));
const out = path.join(root, '3.Knowledge/reports/cineva_campaigns_2026_10_18');
await fs.mkdir(out, { recursive: true });
const esbuild = require('esbuild'), alias = {};
for (const p of JSON.parse(await fs.readFile(path.join(root, '3.Knowledge/scripts/package_upgrade_2026_10_14/snapshot.json'), 'utf8')).packages) alias[p.name] = path.join(root, p.local);
alias.react = path.dirname(require.resolve('react/package.json'));
const files = (await fs.readdir(import.meta.dirname)).filter(f => f.endsWith('.test.ts'));
if (files.length < 3) throw new Error('Foundation, execution and finance suites required');
await fs.writeFile(path.join(import.meta.dirname, 'contracts.entry.ts'), files.map(f => `import './${f}';`).join('\n'));
await esbuild.build({ entryPoints: [path.join(import.meta.dirname, 'contracts.entry.ts')], outfile: path.join(import.meta.dirname, 'contracts.bundle.cjs'), platform: 'node', bundle: true, format: 'cjs', jsx: 'automatic', alias, logLevel: 'warning' });
esbuild.stop();
const result = spawnSync(process.execPath, ['--test', path.join(import.meta.dirname, 'contracts.bundle.cjs')], { encoding: 'utf8' });
await fs.writeFile(path.join(out, 'contracts-results.txt'), result.stdout + result.stderr);
process.stdout.write(result.stdout + result.stderr);
const dir = path.join(root, '1.Frontend/HOTS/src/features');
const counts = await Promise.all((await fs.readdir(dir, { recursive: true })).filter(f => /\.(ts|tsx)$/.test(f)).map(async file => ({ file: file.replaceAll('\\', '/'), lines: (await fs.readFile(path.join(dir, file), 'utf8')).trimEnd().split(/\r?\n/).length })));
counts.sort((a, b) => b.lines - a.lines);
await fs.writeFile(path.join(out, 'line-counts.json'), JSON.stringify(counts, null, 2));
process.stdout.write(JSON.stringify({ limit: 1000, largest: counts[0], exceeded: counts.filter(f => f.lines > 1000) }) + '\n');
if (result.status || counts.some(f => f.lines > 1000)) process.exitCode = 1;
