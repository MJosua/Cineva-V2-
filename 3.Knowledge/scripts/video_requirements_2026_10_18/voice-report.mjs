import fs from 'node:fs/promises';
import path from 'node:path';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const root=path.resolve(import.meta.dirname,'../../..');
const out=path.join(root,'3.Knowledge/reports/voice_requirements_2026_10_18');
const data=JSON.parse(await fs.readFile(path.join(out,'requirements.json'),'utf8'));
const transcript=JSON.parse(await fs.readFile(path.join(out,'transcript.json'),'utf8'));
if(!transcript.segments.length||data.some(r=>r.end>transcript.duration||r.start<0))throw new Error('Missing transcript or invalid timestamp');
const w=Workbook.create(),s=w.worksheets.add('Requirement A dan B');s.showGridLines=false;
s.getRange('A2').values=[['Cineva: requirement dari voice note']];
s.getRange('A2').format.font={name:'Arial',size:14,bold:true,color:'#61411F'};
s.getRange('A3').values=[['Transkripsi otomatis Bahasa Indonesia; kata meragukan tetap ditandai dalam dokumen.']];
s.getRange('A3').format.font={name:'Arial',size:10,italic:true};
s.getRange('A5:E5').values=[['ID','Produk','Detik audio','Requirement','Status / klarifikasi']];
const end=data.length+5;
s.getRange(`A6:E${end}`).values=data.map(r=>[r.id,r.product,`${r.start}–${r.end}`,r.requirement,r.status]);
s.getRange(`A5:E${end}`).format.font={name:'Arial',size:11};
s.getRange(`A5:E${end}`).format.wrapText=true;s.getRange(`A5:E${end}`).format.verticalAlignment='top';
s.getRange('A5:E5').format.fill='#483326';s.getRange('A5:E5').format.font={name:'Arial',size:11,bold:true,color:'#FFFFFF'};
[10,16,17,64,73].forEach((width,i)=>s.getRange(`${String.fromCharCode(65+i)}5:${String.fromCharCode(65+i)}${end}`).format.columnWidth=width);
s.getRange('A5:E5').format.rowHeight=27;
for(let i=6;i<=end;i++){s.getRange(`A${i}:E${i}`).format.rowHeight=64;if(i%2===0)s.getRange(`A${i}:E${i}`).format.fill='#F5F0E7';}
s.getRange(`A${end+2}`).values=[['Sumber: transcript.json dan requirements.json, reports/voice_requirements_2026_10_18.']];
s.getRange(`A${end+2}`).format.font={name:'Arial',size:10,italic:true};
w.recalculate();
await fs.writeFile(path.join(out,'workbook-inspect.json'),(await w.inspect({kind:'table',range:`'Requirement A dan B'!A5:E${Math.min(end,12)}`,include:'values,formulas',tableMaxRows:8,tableMaxCols:5,maxChars:2500})).ndjson);
await fs.writeFile(path.join(out,'workbook-errors.json'),(await w.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?',options:{useRegex:true,maxResults:20},maxChars:500})).ndjson);
await(await SpreadsheetFile.exportXlsx(w)).save(path.join(out,'Cineva_Voice_Requirements.xlsx'));
const preview=await w.render({sheetName:'Requirement A dan B',range:`A1:E${end+2}`,scale:1});
await fs.writeFile(path.join(out,'preview.png'),new Uint8Array(await preview.arrayBuffer()));
process.stdout.write(`Voice requirements: ${data.length} rows exported.\n`);
